// Embeds the skin template models and the temp skin textures into a TypeScript
// module so the plugin bundle is self-contained. Re-run after updating the
// assets: `node scripts/embed-templates.mjs`.
//
// Template bbmodels are stripped of their embedded texture `source` (the texture
// is injected at creation time, sized 64 or 128) and their `meta.model_format`
// is patched to the plugin's own format id, so Codecs.project.parse keeps the
// project on the 3D skin format.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const FORMAT_ID = 'm3sl_3d_skin';

const templates = [
  { id: 'classic', file: 'assets/templates/classic.bbmodel' },
  { id: 'root', file: 'assets/templates/root.bbmodel' },
  { id: 'joint', file: 'assets/templates/joint.bbmodel' },
];
const textures = [
  { size: 64, file: 'assets/textures/temp-64.png' },
  { size: 128, file: 'assets/textures/temp-128.png' },
];

function readTemplate(id, file) {
  const model = JSON.parse(readFileSync(join(root, file), 'utf8'));
  model.meta = model.meta ?? {};
  model.meta.model_format = FORMAT_ID;
  if (Array.isArray(model.textures)) {
    for (const texture of model.textures) {
      delete texture.source;
      delete texture.relative_path;
    }
  }
  return { id, model };
}

function dataUrl(file) {
  const b64 = readFileSync(join(root, file)).toString('base64');
  return `data:image/png;base64,${b64}`;
}

const embeddedTemplates = templates.map(({ id, file }) => readTemplate(id, file));
const embeddedTextures = textures.map(({ size, file }) => ({ size, dataUrl: dataUrl(file) }));

const out = `// AUTO-GENERATED by scripts/embed-templates.mjs — do not edit by hand.
// Sources: assets/templates/*.bbmodel + assets/textures/temp-*.png.

export const NEW_SKIN_FORMAT_ID = ${JSON.stringify(FORMAT_ID)};

/** 模板 bbmodel（已剥离纹理 source，meta 已指向本插件格式）/ Template bbmodels (texture sources stripped, meta patched to this plugin's format). */
export const EMBEDDED_TEMPLATES: Record<string, unknown> = {
${embeddedTemplates.map(({ id, model }) => `  ${JSON.stringify(id)}: ${JSON.stringify(model)},`).join('\n')}
};

/** 对应尺寸的 temp 皮肤纹理（data URL）/ The temp skin textures per size (data URLs). */
export const TEMP_TEXTURE_DATA_URLS: Record<number, string> = {
${embeddedTextures.map(({ size, dataUrl }) => `  ${size}: ${JSON.stringify(dataUrl)},`).join('\n')}
};
`;

mkdirSync(join(root, 'src/assets'), { recursive: true });
writeFileSync(join(root, 'src/assets/embedded.ts'), out, 'utf8');
console.log(
  `embedded ${embeddedTemplates.length} templates and ${embeddedTextures.length} textures -> src/assets/embedded.ts`,
);
