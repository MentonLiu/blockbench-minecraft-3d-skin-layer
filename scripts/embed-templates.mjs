// Embeds the skin template models and the temp skin textures into a TypeScript
// module so the plugin bundle is self-contained. Re-run after updating the
// assets: `node scripts/embed-templates.mjs`.
//
// Template bbmodels are stripped of their embedded texture `source` (the texture
// is injected at creation time, sized 64 or 128) and their `meta.model_format`
// is patched to the plugin's own format id, so Codecs.project.parse keeps the
// project on the 3D skin format.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { prepareTemplateForEmbedding } from './template-assets.mjs';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const FORMAT_ID = 'm3sl_3d_skin';

const skinTypes = ['steve', 'alex'];
const templateIds = ['root', 'classic', 'joint'];
const templates = skinTypes.flatMap(skinType => templateIds.map(id => ({
  skinType,
  id,
  file: `assets/templates/${skinType}/${id}.bbmodel`,
})));
const textures = skinTypes.flatMap(skinType => [64, 128].map(size => ({
  skinType,
  size,
  file: `assets/textures/${skinType}-${size}.png`,
})));

function readTemplate(skinType, id, file) {
  const model = JSON.parse(readFileSync(join(root, file), 'utf8'));
  model.meta = model.meta ?? {};
  model.meta.model_format = FORMAT_ID;
  prepareTemplateForEmbedding(model);
  return { skinType, id, model };
}

function dataUrl(file) {
  const b64 = readFileSync(join(root, file)).toString('base64');
  return `data:image/png;base64,${b64}`;
}

const embeddedTemplates = templates.map(({ skinType, id, file }) => readTemplate(skinType, id, file));
const embeddedTextures = textures.map(({ skinType, size, file }) => ({ skinType, size, dataUrl: dataUrl(file) }));

const templatesBySkinType = skinTypes.map(skinType => {
  const entries = embeddedTemplates.filter(template => template.skinType === skinType);
  return `  ${JSON.stringify(skinType)}: {\n${entries
    .map(({ id, model }) => `    ${JSON.stringify(id)}: ${JSON.stringify(model)},`)
    .join('\n')}\n  },`;
}).join('\n');

const texturesBySkinType = skinTypes.map(skinType => {
  const entries = embeddedTextures.filter(texture => texture.skinType === skinType);
  return `  ${JSON.stringify(skinType)}: {\n${entries
    .map(({ size, dataUrl: url }) => `    ${size}: ${JSON.stringify(url)},`)
    .join('\n')}\n  },`;
}).join('\n');

const out = `// AUTO-GENERATED by scripts/embed-templates.mjs — do not edit by hand.
// Sources: assets/templates/{steve,alex}/*.bbmodel + assets/textures/{steve,alex}-*.png.

export const NEW_SKIN_FORMAT_ID = ${JSON.stringify(FORMAT_ID)};

/** 每种皮肤类型下的模板 / Templates grouped by skin type. */
export const EMBEDDED_TEMPLATES: Record<string, Record<string, unknown>> = {
${templatesBySkinType}
};

/** 每种皮肤类型和尺寸对应的纹理 / Texture data URLs by skin type and size. */
export const TEMP_TEXTURE_DATA_URLS: Record<string, Record<number, string>> = {
${texturesBySkinType}
};
`;

mkdirSync(join(root, 'src/assets'), { recursive: true });
writeFileSync(join(root, 'src/assets/embedded.ts'), out, 'utf8');
console.log(
  `embedded ${embeddedTemplates.length} templates and ${embeddedTextures.length} textures -> src/assets/embedded.ts`,
);
